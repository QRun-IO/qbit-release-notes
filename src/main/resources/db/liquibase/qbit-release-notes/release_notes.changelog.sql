-- changeset qbit-release-notes:1
-- comment: Release notes settings (one row).
CREATE TABLE IF NOT EXISTS release_notes_settings (
   id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   publish_mode VARCHAR(30) NOT NULL DEFAULT 'REQUIRE_APPROVAL',
   audience_type VARCHAR(30) NOT NULL DEFAULT 'ALL_USERS',
   audience_value VARCHAR(200),
   notify_on_publish BOOLEAN DEFAULT TRUE,
   drafting_enabled BOOLEAN DEFAULT TRUE,
   include_platform_updates BOOLEAN DEFAULT TRUE,
   ingest_github BOOLEAN DEFAULT TRUE,
   title_template VARCHAR(200),
   style_guide TEXT,
   create_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
   modify_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- changeset qbit-release-notes:2
-- comment: Releases: one row per application version (unique), the customer note and internal provenance.
CREATE TABLE IF NOT EXISTS release_notes_release (
   id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   app_name VARCHAR(100) NOT NULL,
   version VARCHAR(50) NOT NULL,
   commit_sha VARCHAR(40),
   previous_version VARCHAR(50),
   detected_at TIMESTAMP,
   status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
   title VARCHAR(200),
   summary TEXT,
   audience_type VARCHAR(30),
   audience_value VARCHAR(200),
   published_at TIMESTAMP,
   published_by VARCHAR(100),
   notified_at TIMESTAMP,
   drafted_by VARCHAR(30),
   component_versions TEXT,
   source_log TEXT,
   create_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
   modify_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
   CONSTRAINT release_notes_release_app_version UNIQUE (app_name, version)
);
CREATE INDEX IF NOT EXISTS release_notes_release_status_published ON release_notes_release (app_name, status, published_at);

-- changeset qbit-release-notes:3
-- comment: Release items: customer text plus internal source references; each belongs to one release.
CREATE TABLE IF NOT EXISTS release_notes_item (
   id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   release_id INTEGER NOT NULL,
   category VARCHAR(20) NOT NULL DEFAULT 'IMPROVED',
   item_text TEXT NOT NULL,
   link_url VARCHAR(500),
   screenshot_url VARCHAR(500),
   sort_order INTEGER DEFAULT 100,
   included BOOLEAN DEFAULT TRUE,
   source_type VARCHAR(30) DEFAULT 'MANUAL',
   source_ref VARCHAR(200),
   source_title VARCHAR(500),
   create_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
   modify_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
   CONSTRAINT fk_release_notes_item_release_id FOREIGN KEY (release_id) REFERENCES release_notes_release (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS release_notes_item_release ON release_notes_item (release_id);

-- changeset qbit-release-notes:4
-- comment: Per-user What's new read state.
CREATE TABLE IF NOT EXISTS release_notes_user_state (
   id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   user_id VARCHAR(200) NOT NULL,
   last_seen_at TIMESTAMP,
   create_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
   modify_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
   CONSTRAINT release_notes_user_state_user UNIQUE (user_id)
);

